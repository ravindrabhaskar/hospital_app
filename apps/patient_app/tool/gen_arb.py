import sys  # noqa: E402
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from arb_v13 import register  # noqa: E402
register(k, P, MED)


def build():
    base = os.path.join(os.path.dirname(__file__), '..', 'lib', 'l10n')
    os.makedirs(base, exist_ok=True)
    seen = set()
    for key, *_ in T:
        assert key not in seen, 'duplicate key ' + key
        seen.add(key)
    for idx, lang in [(1, 'en'), (2, 'hi'), (3, 'te')]:
        out = {'@@locale': lang}
        if lang != 'en':
            out['@@x-note'] = ('Keys with GLOSSARY-REVIEW descriptions contain medical terminology and must be '
                               'checked against the clinician-reviewed glossary before release.')
        for row in T:
            key, med = row[0], row[4]
            text = row[idx]
            if key == 'itemsCount':
                text = {'en': '{count, plural, =1{1 item} other{{count} items}}',
                        'hi': '{count, plural, =1{1 आइटम} other{{count} आइटम}}',
                        'te': '{count, plural, =1{1 వస్తువు} other{{count} వస్తువులు}}'}[lang]
            out[key] = text
            meta = {}
            if lang == 'en' and key in P:
                meta['placeholders'] = {n: {'type': t} for n, t in P[key].items()}
            if med and lang != 'en':
                meta['description'] = 'GLOSSARY-REVIEW: medical term, verify with clinical glossary'
            if med and lang == 'en':
                meta['description'] = 'Medical term (translations need clinical glossary review)'
            if meta:
                out['@' + key] = meta
        with open(os.path.join(base, 'app_%s.arb' % lang), 'w', encoding='utf-8') as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
            f.write('\n')
    print('keys:', len(T))


k('itemsCount', '{count} items', '{count} आइटम', '{count} వస్తువులు')
build()
